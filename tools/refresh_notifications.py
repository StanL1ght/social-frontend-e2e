data = json.loads(source.read_text(encoding='utf-8'))
suite = data['suites'][0]
cases = {c['id']: c for c in suite['test_cases']}


def put(case_id, title, description, preconditions, pairs, draft=False):
    case = cases[case_id]
    case.update(title=title, description=description, preconditions=preconditions)
    if draft:
        case['status'] = 'draft'
    case['steps'] = [dict(position=i, action=a, expected_result=e)
                     for i, (a, e) in enumerate(pairs, 1)]


