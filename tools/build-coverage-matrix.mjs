function flattenSuites(suites, result = []) {
  for (const suite of suites ?? []) {
    for (const testCase of suite.test_cases ?? []) result.push({ suite, testCase });
    flattenSuites(suite.suites, result);
  }
  return result;
}

function locateReference(reference) {
  const absolute = path.join(root, reference.file);
  if (!fs.existsSync(absolute)) throw new Error(`Spec does not exist: ${reference.file}`);
  const lines = fs.readFileSync(absolute, 'utf8').split(/\r?\n/);
  const index = lines.findIndex((line) => line.includes(reference.anchor));
  if (index < 0) throw new Error(`Anchor not found in ${reference.file}: ${reference.anchor}`);
  return {
    file: reference.file,
    line: index + 1,
    test: reference.anchor,
  };
}

