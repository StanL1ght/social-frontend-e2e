const cases = flattened.map(({ suite, testCase }, sourceIndex) => {
  const synthetic = testCase.key == null;
  if (synthetic) unkeyedIndex += 1;
  const key = synthetic ? `UNKEYED-${String(unkeyedIndex).padStart(2, '0')}` : testCase.key;
  const override = coverage[key];
  const classification = override?.[0] ?? 'manual/not-automated';
  const entry = {
    sourceIndex: sourceIndex + 1,
    key,
    sourceId: testCase.id ?? null,
    hasStableSourceIdentity: !synthetic,
    suite: suite.title,
    title: testCase.title,
    sourceStatus: testCase.status ?? null,
    sourceAutomationStatus: testCase.automation_status ?? null,
    classification,
    reason: override?.[1] ?? defaultReason(testCase, suite.title),
    specs: (override?.[2] ?? []).map(locateReference),
  };
  return { ...entry, recommendedPriority: recommendedPriority(entry) };
});

