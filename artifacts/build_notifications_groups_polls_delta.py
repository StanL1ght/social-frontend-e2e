import copy
import json
from datetime import datetime
from pathlib import Path


root = Path(__file__).parent
data = copy.deepcopy(json.loads((root / 'Все кейсы — точечная актуализация.json').read_text(encoding='utf-8')))
new_cases = []


def walk(items):
    for item in items:
        yield item
        yield from walk(item.get('suites', []))


def get_suite(title):
    return next(x for x in walk(data['suites']) if x['title'] == title)


def get_case(case_id):
    for item in walk(data['suites']):
        for case in item.get('test_cases', []):
            if case.get('id') == case_id:
                return case
    raise ValueError(case_id)


def make_steps(pairs):
    return [dict(position=i, action=a, expected_result=e) for i, (a, e) in enumerate(pairs, 1)]


def add(suite_title, title, description, preconditions, pairs, status='actual'):
    target = get_suite(suite_title)
    case = {
        'title': title,
        'position': max((x.get('position', 0) for x in target['test_cases']), default=0) + 1,
        'type': 'other', 'status': status, 'severity': 'undefined',
        'priority': 'medium', 'behavior': 'undefined', 'layer': 'unknown',
        'automation_status': 'manual', 'is_flaky': False,
        'to_be_automated': False, 'muted_case': False,
        'description': description, 'preconditions': preconditions,
        'steps': make_steps(pairs),
    }
    target['test_cases'].append(case)
    new_cases.append(case)
    return case


