changed_ids = {7490, 10090, 10095, 10096, 10097, 7529, 7563, 7564}


def filtered_suite(item):
    result = {k: copy.deepcopy(v) for k, v in item.items() if k not in ('test_cases', 'suites')}
    result['test_cases'] = [copy.deepcopy(c) for c in item.get('test_cases', [])
                            if c.get('id') in changed_ids or c in new_cases]
    result['suites'] = [sub for child in item.get('suites', [])
                        if (sub := filtered_suite(child)) is not None]
    return result if result['test_cases'] or result['suites'] else None


