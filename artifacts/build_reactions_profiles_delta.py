import copy
import json
from datetime import datetime
from pathlib import Path


root = Path(__file__).parent
source = json.loads((root / 'Все кейсы — точечная актуализация.json').read_text(encoding='utf-8'))
data = copy.deepcopy(source)
new_cases = []


def walk_suites(suites):
    for suite in suites:
        yield suite
        yield from walk_suites(suite.get('suites', []))


def suite(title):
    return next(s for s in walk_suites(data['suites']) if s['title'] == title)


def get(case_id):
    for item in walk_suites(data['suites']):
        for case in item.get('test_cases', []):
            if case.get('id') == case_id:
                return case
    raise ValueError(case_id)


def steps(pairs):
    return [dict(position=i, action=a, expected_result=e) for i, (a, e) in enumerate(pairs, 1)]


def add(suite_title, title, description, preconditions, pairs):
    target = suite(suite_title)
    case = {
        'title': title,
        'position': max((x.get('position', 0) for x in target['test_cases']), default=0) + 1,
        'type': 'other', 'status': 'draft', 'severity': 'undefined',
        'priority': 'medium', 'behavior': 'undefined', 'layer': 'unknown',
        'automation_status': 'manual', 'is_flaky': False,
        'to_be_automated': False, 'muted_case': False,
        'description': description, 'preconditions': preconditions,
        'steps': steps(pairs),
    }
    target['test_cases'].append(case)
    new_cases.append(case)
    return case


